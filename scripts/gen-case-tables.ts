#!/usr/bin/env tsx
/**
 * Builds the llToLower / llToUpper case tables from Unicode's UnicodeData.txt,
 * version 2.1.5 (vendor/UnicodeData-2.1.5.txt, Unicode License v3).
 *
 * Second Life runs these functions with Mono 2.6's invariant-culture case
 * mapping. Its tables are Unicode 2.1.5's simple case mappings for the code
 * points SLua's lookup covers, minus the code points in UNMAPPED.
 *
 * Outputs:
 *   - packages/vm/src/values/case-tables.ts — the tables for the LSL VM
 *   - packages/vm/native/case-tables.inc    — the same tables for slua.wasm;
 *     scripts/build-slua-wasm.sh puts them in place of the ones in SLua's
 *     VM/src/mono_strings.cpp
 *
 * Run `pnpm gen:case` to regenerate.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
export const UCD_PATH = resolve(ROOT, 'vendor/UnicodeData-2.1.5.txt')
export const TS_PATH = resolve(ROOT, 'packages/vm/src/values/case-tables.ts')
export const INC_PATH = resolve(ROOT, 'packages/vm/native/case-tables.inc')

// SLua's mono_strings.cpp looks code points up in a low table from 0 and a
// high table from U+FF21 to U+FFFF; anything else is left as it is.
const HIGH_START = 0xff21
const LOWER_LOW_END = 0x24cf
const UPPER_LOW_END = 0x24e9

// Unicode 2.1.5 maps these code points, but Mono's invariant culture leaves
// them unchanged in both directions: the Turkish dotted and dotless i, long s,
// the titlecase digraphs, the Greek symbol letter variants, long s with dot
// above, and the Greek letters with ypogegrammeni or prosgegrammeni.
const UNMAPPED: ReadonlyArray<readonly [number, number]> = [
  [0x0130, 0x0131],
  [0x017f, 0x017f],
  [0x01c5, 0x01c5],
  [0x01c8, 0x01c8],
  [0x01cb, 0x01cb],
  [0x01f2, 0x01f2],
  [0x03d0, 0x03d1],
  [0x03d5, 0x03d6],
  [0x03f0, 0x03f2],
  [0x1e9b, 0x1e9b],
  [0x1f80, 0x1faf],
  [0x1fb3, 0x1fb3],
  [0x1fbc, 0x1fbc],
  [0x1fc3, 0x1fc3],
  [0x1fcc, 0x1fcc],
  [0x1ff3, 0x1ff3],
  [0x1ffc, 0x1ffc],
]

const unmapped = (c: number) => UNMAPPED.some(([lo, hi]) => c >= lo && c <= hi)

export interface CaseTables {
  lowerLow: number[]
  lowerHigh: number[]
  upperLow: number[]
  upperHigh: number[]
}

/** One entry per code point, as SLua's C arrays hold them. */
export function buildCaseTables(unicodeData: string): CaseTables {
  const upper = new Map<number, number>()
  const lower = new Map<number, number>()
  for (const line of unicodeData.split('\n')) {
    if (!line.trim()) continue
    const fields = line.split(';')
    const c = parseInt(fields[0]!, 16)
    if (unmapped(c)) continue
    if (fields[12]) upper.set(c, parseInt(fields[12], 16))
    if (fields[13]) lower.set(c, parseInt(fields[13], 16))
  }
  const range = (map: Map<number, number>, from: number, to: number) =>
    Array.from({ length: to - from + 1 }, (_, i) => map.get(from + i) ?? from + i)
  return {
    lowerLow: range(lower, 0, LOWER_LOW_END),
    lowerHigh: range(lower, HIGH_START, 0xffff),
    upperLow: range(upper, 0, UPPER_LOW_END),
    upperHigh: range(upper, HIGH_START, 0xffff),
  }
}

/** The code point, mapped pairs of a table, for the code points it changes. */
export function changedPairs(table: number[], start: number): number[] {
  return table.flatMap((m, i) => (m === start + i ? [] : [start + i, m]))
}

const HEADER = [
  'AUTO-GENERATED by scripts/gen-case-tables.ts — do not edit by hand.',
  "Source: vendor/UnicodeData-2.1.5.txt (Unicode 2.1.5's simple case mappings,",
  'Unicode License v3; see NOTICE). Run `pnpm gen:case` to regenerate.',
]

export function renderTs(t: CaseTables): string {
  const pairs = (name: string, doc: string, values: number[]) =>
    `/** ${doc} */\nexport const ${name}: ReadonlyArray<number> = [${values.join(',')}]\n`
  return [
    ...HEADER.map((l) => `// ${l}`),
    '//',
    '// Each table is a flat list of code point, mapped pairs for the code points',
    '// whose mapping differs from the code point itself.',
    '',
    pairs('lowerPairs', 'llToLower.', [...changedPairs(t.lowerLow, 0), ...changedPairs(t.lowerHigh, HIGH_START)]),
    pairs('upperPairs', 'llToUpper.', [...changedPairs(t.upperLow, 0), ...changedPairs(t.upperHigh, HIGH_START)]),
  ].join('\n')
}

export function renderInc(t: CaseTables): string {
  const array = (name: string, values: number[]) => {
    const rows: string[] = []
    for (let i = 0; i < values.length; i += 16) rows.push(`    ${values.slice(i, i + 16).join(',')},`)
    return `static const uint16_t ${name} [] = {\n${rows.join('\n')}\n};\n`
  }
  return [
    ...HEADER.map((l) => `// ${l}`),
    '',
    array('ToLowerDataLow', t.lowerLow),
    array('ToLowerDataHigh', t.lowerHigh),
    array('ToUpperDataLow', t.upperLow),
    array('ToUpperDataHigh', t.upperHigh),
  ].join('\n')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tables = buildCaseTables(readFileSync(UCD_PATH, 'utf8'))
  writeFileSync(TS_PATH, renderTs(tables))
  writeFileSync(INC_PATH, renderInc(tables))
  console.log(`wrote ${TS_PATH} and ${INC_PATH}`)
}

const f32 = Math.fround

function shortest(v: number) {
  if (Object.is(v, -0)) return '-0'
  if (!Number.isFinite(v) || v === 0) return String(v)
  for (let digits = 1; digits <= 9; digits++) {
    const rounded = Number(v.toPrecision(digits))
    if (f32(rounded) === v) return String(rounded)
  }
  return String(v)
}

/** Turns each "mantissa p exponent" float of a probe line into its shortest decimal. */
const readable = (line: string) =>
  line.replace(/-?\d+p-?\d+/g, (t) => { const [m, e] = t.split('p'); return shortest(Number(m) * 2 ** Number(e)) })

const EXACT = `
  // The exact value of a float: mantissa, "p", exponent of two.
  string B(float f) {
    if (f == 0.0) return llList2String(llParseString2List(llList2CSV([f]), ["."], []), 0);
    string s = "";
    if (f < 0.0) { s = "-"; f = -f; }
    integer e = 0;
    while (f < 8388608.0) { f *= 2.0; --e; }
    while (f >= 16777216.0) { f *= 0.5; ++e; }
    return s + (string)((integer)f) + "p" + (string)e;
  }
  string BR(rotation r) { return "<" + B(r.x) + "," + B(r.y) + "," + B(r.z) + "," + B(r.s) + ">"; }
`

/** llRotBetween of each pair of vectors, one exact line each. */
async function rotBetween(pairs: string[]) {
  const s = await run(EXACT + `
    default {
      state_entry() {
        list vs = [${pairs.join(', ')}];
        integer i;
        for (i = 0; i < llGetListLength(vs); i += 2) llSay(0, BR(llRotBetween(llList2Vector(vs, i), llList2Vector(vs, i + 1))));
      }
    }`)
  return said(s).map(readable)
}


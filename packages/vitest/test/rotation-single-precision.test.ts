/** Each line the script said, by its label. */
async function said(source: string) {
  const s = await loadScript({ source })
  s.start()
  return new Map(s.chat.filter((c) => c.channel === 0).map((c) => {
    const [label, rest] = c.text.split(' | ')
    return [label!, rest!]
  }))
}
const vectors = (csv: string) => csv.match(/<[^>]*>/g)!

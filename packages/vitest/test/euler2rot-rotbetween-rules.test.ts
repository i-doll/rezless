const said = (s: { chat: ReadonlyArray<{ channel: number; text: string }> }) =>
  s.chat.filter((c) => c.channel === 0).map((c) => c.text)

async function run(source: string) {
  const s = await loadScript({ source })
  s.start()
  return s
}

async function runSlua(source: string) {
  const s = await loadScript({ language: 'slua', filename: 'probe.luau', source })
  s.start()
  return s
}

const f32 = Math.fround

const EXACT = `
  // The exact value of a float: mantissa, "p", exponent of two.
  string B(float f) {
    if (f == 0.0) return llList2String(llParseString2List(llList2CSV([f]), ["."], []), 0);
    string s = "";
    if (f < 0.0) { s = "-"; f = -f; }
    integer e = 0;
    while (f < 8388608.0) { f *= 2.0; --e; }
    while (f >= 16777216.0) { f *= 0.5; ++e; }
    return s + (string)((integer)f) + "p" + (string)e;
  }
  string BR(rotation r) { return B(r.x) + "," + B(r.y) + "," + B(r.z) + "," + B(r.s); }
`

/** A "mantissa p exponent" float back as a number, keeping a negative zero. */
function fromExact(t: string) {
  if (t === '0') return 0
  if (t === '-0') return -0
  const negative = t.startsWith('-')
  const [m, e] = (negative ? t.slice(1) : t).split('p')
  const v = Number(m) * 2 ** Number(e)
  return negative ? -v : v
}

/** What rezless gives for each call, read back exactly, in chunks a script can hold. */
async function rotations(calls: string[]) {
  const got: number[][] = []
  for (let start = 0; start < calls.length; start += 50) {
    const s = await run(EXACT + `
      default {
        state_entry() {
          ${calls.slice(start, start + 50).map((c) => `llSay(0, BR(${c}));`).join('\n          ')}
        }
      }`)
    got.push(...said(s).map((line) => line.split(',').map(fromExact)))
  }
  return got
}


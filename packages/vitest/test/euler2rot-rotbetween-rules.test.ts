describe('llEuler2Rot', () => {
  it('drops the small turns of an axis whose matrix diagonal is within 1e-10 of 1', async () => {
    const got = await rotations(EULER2ROT.map(([e]) => `llEuler2Rot(<${e.join(', ')}>)`))
    // In-world: 305 rotations. 24 turns about x each from 1.125, 0.4833984375, 3.1275 and 6.0066
    // radians, one float apart; 24 angles from 0.0258 to 6.0066 about each axis, both ways; and 73
    // small turns about two or three axes: (u, u, u) for u from 9e-6 to 1.3e-5, (u, u, 2u) for u
    // from 6e-6 to 8e-6, (u, u, 0) for u from 1.4e-5 to 2.2e-5, and 30 random ones within 2e-5.
    // An SLua script gave the same for the 144 turns about one axis, negative zeros included.
    //
    // Each angle is stepped to 1e-7 degrees and the rotation goes through a matrix. Where a
    // diagonal entry is within 1e-10 of 1 or -1, the rest of its row and column count as zero:
    // <7e-6, 7e-6, 1.4e-5> keeps only the turn about z, though 1.4e-5 about z alone is dropped,
    // and <1e-5, 1e-5, 1e-5> keeps all three, though <1e-5, 1e-5, 9e-6> keeps none. Every zero
    // below comes out as measured, its sign too: when s is the largest part, a zero y takes the
    // sign of x * z, so <-1.546875, 0, 0> gives <-0.69860, -0, 0, 0.71551>.
    for (const [i, [, q]] of EULER2ROT.entries()) {
      const r = got[i]!
      for (let k = 0; k < 4; k++) {
        if (q[k] === 0 || r[k] === 0) expect(Object.is(r[k], q[k]), `${EULER2ROT[i]![0]} part ${k}`).toBe(true)
      }
    }
    // The last bits are still open. With the whole turns taken off in degrees, matrices in single
    // precision with the rows made orthogonal as llRot2Euler makes them give 256 of these exactly
    // (233 before), and the rest within 2.1e-7.
    const exact = EULER2ROT.filter(([, q], i) => q.every((v, k) => got[i]![k] === f32(v))).length
    const worst = Math.max(...EULER2ROT.flatMap(([, q], i) => q.map((v, k) => Math.abs(got[i]![k]! - f32(v)))))
    expect(exact).toBe(256)
    expect(worst).toBeLessThan(2.1e-7)
  })
})

describe('llEuler2Rot of NaN, infinite and huge angles', () => {
  it('turns a NaN or infinite angle by about 25.07 degrees', async () => {
    const s = await run(EXACT + `
      default {
        state_entry() {
          float nan = (float)"nan";
          float inf = (float)"inf";
          list es = [<nan, 0, 0>, <0, nan, 0>, <0, 0, nan>, <inf, 0, 0>, <-inf, 0, 0>, <0, 0, inf>];
          integer i;
          for (i = 0; i < llGetListLength(es); ++i) llSay(0, BR(llEuler2Rot(llList2Vector(es, i))));
        }
      }`)
    // In-world: each gave a turn about its axis of 2 * atan(14565665p-26 / 16377273p-24), about
    // 25.07 degrees: the angle stepped to 1e-7 degrees through a 64-bit integer, which a NaN or
    // infinite value turns into its lowest value, -2^63.
    const x = '14565665p-26'
    const s1 = '16377273p-24'
    expect(said(s)).toEqual([
      `${x},0,0,${s1}`, `0,${x},0,${s1}`, `0,0,${x},${s1}`, `${x},0,0,${s1}`, `${x},0,0,${s1}`, `0,0,${x},${s1}`,
    ])
  })

  const turn = async (angle: string) => {
    const [[x, , , s]] = await rotations([`llEuler2Rot(<${angle}, 0, 0>)`])
    return (2 * Math.atan2(x!, s!) * 180) / Math.PI
  }

  it('reduces a large angle by whole turns, and turns one too large for the step as a NaN one', async () => {
    // In-world: <1e6, 0, 0> turned -20.487 degrees, 1e6 radians less whole turns, and 1e20, 1e29,
    // 1e30 and 3e38 radians the 25.07 degrees of a NaN angle: in 1e-7 degree steps they don't fit
    // a 64-bit integer.
    expect(await turn('1e6')).toBeCloseTo(-20.487, 3)
    for (const angle of ['1e20', '1e29', '1e30', '3e38']) expect(await turn(angle)).toBeCloseTo(25.071, 3)
  })

  it('steps each NaN or infinite angle the same way when there are several', async () => {
    const got = await rotations([
      'llEuler2Rot(<(float)"nan", (float)"nan", 0>)', 'llEuler2Rot(<(float)"nan", (float)"nan", (float)"nan">)',
      'llEuler2Rot(<(float)"inf", (float)"inf", (float)"inf">)', 'llEuler2Rot(<(float)"nan", 0.5, 0>)',
      'llEuler2Rot(<0.3, 0.2, (float)"nan">)', 'llEuler2Rot(<(float)"inf", -(float)"inf", 1.0>)',
    ])
    // In-world (2026-11-23, Mono), printed exactly.
    const want = [
      ['14218442p-26', '14218442p-26', '12645638p-28', '15986864p-24'], ['8482771p-25', '10793449p-26', '8482771p-25', '15434219p-24'],
      ['8482771p-25', '10793449p-26', '8482771p-25', '15434219p-24'], ['14112855p-26', '16207211p-26', '14414415p-28', '15868143p-24'],
      ['11178461p-26', '8601535p-27', '15307483p-26', '16058148p-24'], ['9647271p-25', '11322342p-27', '16716222p-25', '13650877p-24'],
    ].map((q) => q.map(fromExact))
    for (const [i, q] of want.entries()) for (const [k, v] of q.entries()) expect(Math.abs(got[i]![k]! - v)).toBeLessThan(6e-8)
  })

  // In-world: 1e7, 1e8 and 1e9 radians turned 163.131, -32.692 and 145.082 degrees, 1e10 radians
  // 18.823 degrees, and 1.6e10 radians the 25.07 degrees of a NaN angle, though its steps fit a
  // 64-bit integer (1.7e10 and 2e10 don't). The whole turns come off in degrees, truncated to a
  // 32-bit integer and multiplied back as a float, which is off by multiples of 8 degrees here, and
  // 1.6e10 radians is more turns than a 32-bit integer holds. More of these are in euler2rot-turns.test.ts.
  it('turns 1e7 to 1.6e10 radians as Second Life does', async () => {
    const want: Array<[string, number]> = [['1e7', 163.131], ['1e8', -32.692], ['1e9', 145.082], ['1e10', 18.823], ['1.6e10', 25.071]]
    for (const [angle, degrees] of want) expect(await turn(angle)).toBeCloseTo(degrees, 2)
  })
})


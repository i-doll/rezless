describe('faces of a shape', () => {
  it('counts faces as Second Life builds them', async () => {
    const s = await run(`
      default {
        state_entry() {
          ${FACE_COUNTS.map(([shape]) => `llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_TYPE] + ${shape}); llSay(0, (string)llGetNumberOfSides());`).join('\n          ')}
        }
      }`)
    // In-world: each shape set on a box and counted. A profile cut makes cut faces only when it
    // leaves under 99% of the profile, and a sphere's dimple whenever it leaves under 100%. A box
    // or prism has a side for each edge its cut reaches. A torus, tube or ring gets a top and a
    // bottom from a path cut, a twist that differs end to end, or a taper, a skew or a change in
    // path radius of more than about 0.001. A radius offset changes the radius by the offset
    // times half of one minus hole size y, so with a hole size of 0.25 the step is near 0.0027.
    // A sphere gets them from a path cut or such a twist.
    expect(said(s).map(Number)).toEqual(FACE_COUNTS.map(([, n]) => n))
  })

  it('keeps a negative zero in a path cut and a twist, and drops it from hollow and a profile cut', async () => {
    const s = await run(`
      default {
        state_entry() {
          ${NEGATIVE_ZEROS.map(([shape]) => `llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_TYPE] + ${shape}); llSay(0, llList2CSV(llGetPrimitiveParams([PRIM_TYPE])));`).join('\n          ')}
        }
      }`)
    expect(said(s).map((line) => line.replace(/(\.\d)00000\b/g, '$1'))).toEqual(NEGATIVE_ZEROS.map(([, read]) => read))
  })

  it('numbers a top first, then the sides, the inner face, the bottom and the cut faces', async () => {
    const s = await run(`
      string colours() {
        integer n = llGetNumberOfSides(); integer i; string s = (string)n + ":";
        for (i = 0; i < n; ++i) { vector c = llList2Vector(llGetPrimitiveParams([PRIM_COLOR, i]), 0); s += (string)llRound(c.x * 20.0) + "."; }
        return s;
      }
      go(list from, list to) {
        llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_TYPE] + from);
        integer n = llGetNumberOfSides(); integer i;
        for (i = 0; i < n; ++i) llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_COLOR, i, <(i + 1) * 0.05, 0, 0>, 1.0]);
        llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_TYPE] + to);
        llSay(0, colours());
      }
      default {
        state_entry() {
          ${FACE_ORDER.flatMap(([from]) => TARGETS.map((to) => `go(${from}, ${to});`)).join('\n          ')}
        }
      }`)
    // In-world: each shape had face i painted with red (i + 1) / 20, was changed to a plain box,
    // a hollow cut box, a hollow sphere with a cut and a dimple, and a hollow torus with both
    // cuts, and had its colours read back. A sphere with only a path cut or a twist has a top,
    // a side and a bottom. One with only a dimple has the side first and then two cut faces,
    // and a hollow one the side, the inner face and two cut faces.
    expect(said(s)).toEqual(FACE_ORDER.flatMap(([, shown]) => shown))
  })

  it('gives a box with a NaN cut end no faces, and white untextured ones afterwards', async () => {
    const s = await run(`
      default {
        state_entry() {
          float inf = 1e38 * 1e38;
          float nan = inf - inf;
          list box = [PRIM_TYPE, PRIM_TYPE_BOX, 0, <0, 1, 0>, 0.0, ZERO_VECTOR, <1, 1, 0>, ZERO_VECTOR];
          llSetLinkPrimitiveParamsFast(LINK_THIS, box + [PRIM_COLOR, ALL_SIDES, <0.5, 0, 0>, 0.5, PRIM_TEXTURE, ALL_SIDES, TEXTURE_BLANK, <2, 2, 0>, <0.25, 0.25, 0>, 0.5]);
          llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_TYPE, PRIM_TYPE_BOX, 0, <0.2, nan, 0>, 0.0, ZERO_VECTOR, <1, 1, 0>, ZERO_VECTOR]);
          llSay(0, llList2CSV([llGetNumberOfSides(), llGetListLength(llGetPrimitiveParams([PRIM_COLOR, ALL_SIDES])), llGetListLength(llGetPrimitiveParams([PRIM_COLOR, 0])),
            llGetAlpha(ALL_SIDES), llGetAlpha(0), llGetColor(ALL_SIDES), llGetColor(0), llGetTexture(0)]));
          llSetLinkPrimitiveParamsFast(LINK_THIS, box);
          llSay(0, llList2CSV([llGetNumberOfSides(), llGetColor(0), llGetColor(5)] + llGetPrimitiveParams([PRIM_TEXTURE, 0, PRIM_TEXTURE, 5])));
        }
      }`)
    // In-world: a box with every face painted and textured, then a NaN cut end, then a plain box
    // again. This was measured on a box only. The same NaN on a cylinder took the region down,
    // so no curved shape was given one.
    expect(said(s)).toEqual([
      '0, 0, 0, 1.000000, 1.000000, <1.000000, 1.000000, 1.000000>, <1.000000, 1.000000, 1.000000>, 00000000-0000-0000-0000-000000000000',
      '6, <1.000000, 1.000000, 1.000000>, <1.000000, 1.000000, 1.000000>, 00000000-0000-0000-0000-000000000000, <1.000000, 1.000000, 0.000000>, <0.000000, 0.000000, 0.000000>, 0.000000, 00000000-0000-0000-0000-000000000000, <1.000000, 1.000000, 0.000000>, <0.000000, 0.000000, 0.000000>, 0.000000',
    ])
  })
})

// Each probe first set a shape with every value away from its default (BASES), then the same
// shape with one value replaced, and read PRIM_TYPE back. "v" is the value read back and "n" is
// llGetNumberOfSides. "ALL" is the whole shape, shown when another value changed too.
const SHAPE_PROBE = EXACT + `
  list A;
  list base(integer kind) {
    BASE_CASES
    return [];
  }
  string X(list l, integer i) {
    integer t = llGetListEntryType(l, i);
    if (t == TYPE_VECTOR) return BV(llList2Vector(l, i));
    if (t == TYPE_FLOAT) return B(llList2Float(l, i));
    return llList2String(l, i);
  }
  f(integer idx, list full) {
    llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_TYPE] + base(llList2Integer(full, 0)));
    llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_TYPE] + full);
    llSay(0, "n=" + (string)llGetNumberOfSides() + " v=" + X(llGetPrimitiveParams([PRIM_TYPE]), idx));
  }
  t(integer kind, integer idx, list v) {
    A = base(kind);
    llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_TYPE] + A);
    list ra = llGetPrimitiveParams([PRIM_TYPE]);
    llSetLinkPrimitiveParamsFast(LINK_THIS, [PRIM_TYPE] + llListReplaceList(A, v, idx, idx));
    list rt = llGetPrimitiveParams([PRIM_TYPE]);
    string s = "n=" + (string)llGetNumberOfSides() + " v=" + X(rt, idx);
    if (llList2CSV(llDeleteSubList(rt, idx, idx)) != llList2CSV(llDeleteSubList(ra, idx, idx))) s += " ALL=" + llList2CSV(rt);
    llSay(0, s);
  }
`.replace('BASE_CASES', BASES.map((b, kind) => `if (kind == ${kind}) return ${b};`).join('\n    '))

describe('PRIM_TYPE limits', () => {
  it.each(Object.entries(SHAPE_TABLE))('%s', async (_name, rows) => {
    const s = await run(SHAPE_PROBE + `
      default {
        state_entry() {
          float inf = 1e38 * 1e38;
          float nan = inf - inf;
          ${rows.map(([call]) => call + ';').join('\n          ')}
        }
      }`)
    expect(said(s).map(readable)).toEqual(rows.map(([, read]) => read))
  })
})


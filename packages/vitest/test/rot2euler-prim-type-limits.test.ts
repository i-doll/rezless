describe('llRot2Euler', () => {
  const GENERATOR = `
    integer seed = 1;
    integer rnd() { seed = (seed * 75 + 74) % 65537; return seed; }
  `

  it('reads the angles from a single-precision matrix with orthogonal rows', async () => {
    const s = await run(EXACT + GENERATOR + `
      default {
        state_entry() {
          integer i;
          for (i = 0; i < 40; ++i) {
            float x = (rnd() % 2049 - 1024) / 1024.0;
            float y = (rnd() % 2049 - 1024) / 1024.0;
            float z = (rnd() % 2049 - 1024) / 1024.0;
            float w = (rnd() % 2049 - 1024) / 1024.0;
            llSay(0, BV(llRot2Euler(<x, y, z, w>)));
          }
        }
      }`)
    // In-world: 120 rotations with each component a random multiple of 1/1024 from -1 to 1. These
    // are the first 40. All 120 match to the last bit, as do the 394 other rotations measured.
    expect(said(s).map(readable)).toEqual(GENERAL)
  })

  it('does not normalise a rotation within 1e-6 of unit length', async () => {
    const s = await run(EXACT + GENERATOR + `
      default {
        state_entry() {
          integer i;
          for (i = 0; i < 480; ++i) rnd();
          for (i = 0; i < 20; ++i) {
            float x = (rnd() % 1101 - 550) / 1024.0;
            float y = (rnd() % 1101 - 550) / 1024.0;
            float z = (rnd() % 1101 - 550) / 1024.0;
            float w = llSqrt(1.0 - x * x - y * y - z * z);
            if (rnd() & 1) w = -w;
            llSay(0, BV(llRot2Euler(<x, y, z, w>)));
          }
        }
      }`)
    // In-world: 80 unit rotations, with x, y and z random multiples of 1/1024 and s the square
    // root that makes the length 1. These are the first 20.
    expect(said(s).map(readable)).toEqual(UNIT)
    // In-world: <0.75, -0.4375, 0.1875, 0.3125> made unit length, then times 1, 2, 0.5, 1024,
    // 1/1024, 3, 1.0000005, 1.000001, 1.000002, 0.999999, 0.999998, 1.00001, 1e-10 and 1e10,
    // and <0.1, 0.2, 0.3, 0.9> times 1, 3, 1e-10 and 1e10. A power of two changes nothing. Times
    // 1.0000005 and 1.000001 the rotation is used as it is and all three angles move. Any other
    // factor is normalised away, which can move the small y by a few floats. Times 1e-10 it
    // reads as no rotation.
    expect(await eulers(SCALED.map(([q]) => q))).toEqual(SCALED.map(([, e]) => e))
  })

  it('takes y from an arcsine, locks within 0.29 degrees of the poles and gives 180 degrees for -180', async () => {
    // In-world: turns about one axis of 0.1, 1, 30, 45, 60, 89, 89.9, 89.97, 89.99, 90, 90.01,
    // 91, 120, 179.99, 180, 181, 270 and 540 degrees, built from the sine and cosine of half the
    // angle, then <a, 0, 0, 1> and the same about y and z for a from 0.001 to 1000. A turn of
    // 89.9 degrees about y reads 89.90309, and 89.99 and 90.01 read 90. Past 90 degrees about y,
    // x and z read 180 degrees and never -180.
    expect(await eulers(SINGLE_AXIS.map(([q]) => q))).toEqual(SINGLE_AXIS.map(([, e]) => e))
    // In-world: rotations at and near y = +-PI/2, half turns, lengths from 1e-30 to 3e38, and
    // eight general rotations. <0.3, -0.3, 0.3, -0.3> reads z = -PI/2.
    expect(await eulers(LITERAL.map(([q]) => q))).toEqual(LITERAL.map(([, e]) => e))
    // In-world: llEuler2Rot(<0.3, y, 0.5>) for y 0.05, 0.1, 0.3 and 1 degrees short of 90 and
    // of -90 degrees, given here as the rotations it returned. At 0.05 and 0.1 degrees x is 0
    // and z holds both turns. At 0.3 degrees and 1 degree x and z are apart again.
    expect(await eulers(NEAR_POLES.map(([q]) => q))).toEqual(NEAR_POLES.map(([, e]) => e))
  })

  it('reads a rotation with a NaN or an infinity as no rotation', async () => {
    // In-world: these five rotations, each <0, 0, 0>.
    expect(await eulers(NOT_FINITE.map(([q]) => q))).toEqual(NOT_FINITE.map(([, e]) => e))
  })

  it('gives the same angles in SLua', async () => {
    const s = await runSlua(`
      local seed = 1
      local function rnd() seed = (seed * 75 + 74) % 65537; return seed end
      local function say(v) ll.Say(0, string.format("%.9g,%.9g,%.9g", v.x, v.y, v.z)) end
      for i = 1, 20 do
        local x = (rnd() % 2049 - 1024) / 1024
        local y = (rnd() % 2049 - 1024) / 1024
        local z = (rnd() % 2049 - 1024) / 1024
        local w = (rnd() % 2049 - 1024) / 1024
        say(ll.Rot2Euler(quaternion(x, y, z, w)))
      end
      local qs = {quaternion(0.3,-0.3,0.3,-0.3), quaternion(0.5,0.5,0.5,0.5), quaternion(0,0.70710677,0,0.70710677), quaternion(0.6,0.8,0,0), quaternion(0,0,0,0),
        quaternion(0.1,0.2,0.3,0.9), quaternion(12,-7,3,5), quaternion(0.001,0.7071,0,0.7071), quaternion(8.7266463e-4,0,0,1), quaternion(0.02,0,0,1), quaternion(0,0,0.38268343,0.92387953)}
      for _, q in qs do say(ll.Rot2Euler(q)) end`)
    // In-world: an SLua script with the first 60 rotations of the first test and these 11. All 71
    // read the same as under Mono.
    expect(said(s).map((line) => line.split(',').map((t) => shortest(f32(Number(t)))).join(','))).toEqual(SLUA)
  })
})


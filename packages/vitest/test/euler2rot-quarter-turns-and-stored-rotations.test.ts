function fromExact(t: string) {
  if (t === '0') return 0
  if (t === '-0') return -0
  const negative = t.startsWith('-')
  const [m, e] = (negative ? t.slice(1) : t).split('p')
  const v = Number(m) * 2 ** Number(e)
  return negative ? -v : v
}

